import { build } from "esbuild";
import * as fs from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL(".", import.meta.url));
const extension = new URL("../../plugins/agile-agents-core/extensions/solution-profile/", import.meta.url);
const check = process.argv.includes("--check");
const result = await build({
    absWorkingDir: root,
    stdin: {
        contents: 'export { isAlias, isMap, isScalar, isSeq, parseDocument, visit } from "yaml";',
        resolveDir: root,
        sourcefile: "yaml-entry.mjs",
    },
    bundle: true,
    format: "cjs",
    platform: "node",
    target: "node22",
    outfile: "yaml.cjs",
    write: false,
    banner: { js: "// Generated by npm run build. See yaml.LICENSE for the upstream license." },
});
const outputs = [
    ["yaml.cjs", result.outputFiles[0].contents],
    ["yaml.LICENSE", await fs.readFile(new URL("node_modules/yaml/LICENSE", import.meta.url))],
];
for (const [file, contents] of outputs) {
    const target = new URL(file, extension);
    if (check) {
        if (!(await fs.readFile(target)).equals(Buffer.from(contents)))
            throw new Error(`${file} is stale. Run npm run build and include the generated files.`);
    } else await fs.writeFile(target, contents);
}
